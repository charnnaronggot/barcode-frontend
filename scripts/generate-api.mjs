import fs from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";
for (const host of ["command", "query", "report"]) {
  const source =
    process.env[host.toUpperCase() + "_OPENAPI_URL"] ||
    "openapi/" + host + ".json";
  const document = source.startsWith("http")
    ? await fetch(source).then((r) => {
        if (!r.ok) throw new Error("OpenAPI unavailable: " + r.status);
        return r.json();
      })
    : JSON.parse(await fs.readFile(source, "utf8"));
  await fs.mkdir("openapi", { recursive: true });
  await fs.mkdir("src/core/generated/" + host, { recursive: true });
  await fs.writeFile(
    "openapi/" + host + ".json",
    JSON.stringify(document, null, 2) + "\n",
  );
  await fs.writeFile(
    "src/core/generated/" + host + "/schema.d.ts",
    astToString(
      await openapiTS(document, { propertiesRequiredByDefault: true }),
    ),
  );
  const operations = {};
  for (const [path, item] of Object.entries(document.paths))
    for (const method of Object.keys(item))
      if (["get", "post", "put", "delete", "patch"].includes(method))
        operations[method.toUpperCase() + " " + path] = path;
  await fs.writeFile(
    "src/core/generated/" + host + "/endpoints.ts",
    "// Generated by npm run api. Do not edit.\nexport const endpoints = " +
      JSON.stringify(operations, null, 2) +
      " as const;\n",
  );
}
